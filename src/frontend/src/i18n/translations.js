export const dictionaries = { en, ru };

function lookup(dict, path) {
  return path.split('.').reduce((acc, key) => (acc && acc[key] != null ? acc[key] : null), dict);
}

/** Resolves `a.b.c`, falls back to English, then interpolates `{name}` params. */
export function translate(locale, path, params) {
  const dict = dictionaries[locale] || dictionaries.en;
  let value = lookup(dict, path) ?? lookup(dictionaries.en, path);
  if (typeof value === 'string' && params) {
    value = value.replace(/\{(\w+)\}/g, (match, key) => (params[key] != null ? String(params[key]) : match));
  }
  return value;
}
